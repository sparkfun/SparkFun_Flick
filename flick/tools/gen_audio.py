#!/usr/bin/env python3
"""Generate the Audio library proxies from api/audio_api.txt (Teensy 4.x, ABI 1.8).

Outputs:
  sdk/include/baseline_audio.h                    sketch-side classes with the Audio
                                                  library's names and methods; each call
                                                  goes through bl_audio_call()
  chips/imxrt1062/baseline/bl_audio_dispatch.inc  Baseline: one function that constructs
                                                  an object by type number, one that calls
                                                  a method by number

Usage:  python flick/tools/gen_audio.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "api" / "audio_api.txt"
OUT_SDK = ROOT / "sdk" / "include" / "baseline_audio.h"
OUT_DISPATCH = ROOT / "chips" / "imxrt1062" / "baseline" / "bl_audio_dispatch.inc"
HEADER = "/* GENERATED by tools/gen_audio.py from api/audio_api.txt - DO NOT EDIT */\n"

BASE_METHODS = [(1000, "float", "processorUsage"), (1001, "float", "processorUsageMax"),
                (1002, "void", "processorUsageMaxReset")]


class Param:
    def __init__(self, text):
        text = text.strip()
        self.default = None
        if "=" in text:
            text, self.default = (t.strip() for t in text.split("=", 1))
        m = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)$", text)
        if not m:
            sys.exit(f"error: bad parameter '{text}'")
        self.type, self.name = m.group(1).strip(), m.group(2)
        self.enum = self.type.startswith("enum:")
        if self.enum:
            self.type = self.type[5:]

    def member(self):
        return member_of(self.type, self.enum)

    def sdk_decl(self):
        t = "int" if self.enum else self.type
        return f"{t} {self.name}" + (f" = {self.default}" if self.default else "")

    def baseline_arg(self, i):
        m = self.member()
        if m == "p":
            return f"({self.type})a[{i}].p"
        if m == "f":
            return f"a[{i}].f"
        if self.type == "bool":
            return f"a[{i}].i != 0"
        return f"({self.type})a[{i}].i"

    def sdk_store(self, i):
        m = self.member()
        if m == "p":
            return f"a[{i}].p = (const void *){self.name};"
        if m == "f":
            return f"a[{i}].f = (float){self.name};"
        return f"a[{i}].i = (int32_t){self.name};"


def member_of(ctype, enum=False):
    if enum:
        return "i"
    if "*" in ctype:
        return "p"
    if ctype in ("float", "double"):
        return "f"
    return "i"


def parse_params(text):
    text = text.strip()
    if text in ("", "void", "-"):
        return []
    return [Param(p) for p in text.split(",")]


def parse_spec():
    classes, cur = [], None
    for n, raw in enumerate(SPEC.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip() if not raw.lstrip().startswith("#") else ""
        if not line:
            continue
        parts = [p.strip() for p in line.split("|")]
        if parts[0].startswith("class "):
            name = parts[0][6:].strip()
            cur = {"name": name, "type": int(parts[1]), "kind": parts[2],
                   "ctor": parse_params(parts[3]), "cond": None if parts[4] == "-" else parts[4],
                   "methods": []}
            classes.append(cur)
        else:
            if cur is None or len(parts) != 4:
                sys.exit(f"{SPEC.name}:{n}: expected '<number> | <return> | <name> | <params>'")
            cur["methods"].append({"id": int(parts[0]), "ret": parts[1], "name": parts[2],
                                   "params": parse_params(parts[3])})
    types = [c["type"] for c in classes]
    if len(set(types)) != len(types):
        sys.exit("error: duplicate class type number")
    for c in classes:
        ids = [m["id"] for m in c["methods"]]
        if len(set(ids)) != len(ids) or any(i >= 1000 for i in ids):
            sys.exit(f"error: {c['name']}: duplicate method number, or one >= 1000")
    return classes


# ---------------------------------------------------------------- sketch side

SDK_PROLOGUE = r'''/*
 * baseline_audio.h - the Teensy Audio library for sketches (Teensy 4.x, ABI 1.8).
 * Included by <Audio.h>. The objects live in Baseline; each class here holds a
 * handle and forwards its methods through bl_audio_call(). Names, methods and
 * constants are the Audio library's, so code from PJRC's Audio System Design
 * Tool compiles as it is.
 *
 * Not supported (yet): subclassing AudioStream for your own objects, and the
 * objects not listed below.
 */
#ifndef BASELINE_AUDIO_H
#define BASELINE_AUDIO_H

#ifdef __cplusplus

#define AUDIO_BLOCK_SAMPLES     128
#define AUDIO_SAMPLE_RATE_EXACT 44117.64706f
#define AUDIO_SAMPLE_RATE       AUDIO_SAMPLE_RATE_EXACT

#define WAVEFORM_SINE              0
#define WAVEFORM_SAWTOOTH          1
#define WAVEFORM_SQUARE            2
#define WAVEFORM_TRIANGLE          3
#define WAVEFORM_ARBITRARY         4
#define WAVEFORM_PULSE             5
#define WAVEFORM_SAWTOOTH_REVERSE  6
#define WAVEFORM_SAMPLE_HOLD       7
#define WAVEFORM_TRIANGLE_VARIABLE 8
#define WAVEFORM_BANDLIMIT_SAWTOOTH  9
#define WAVEFORM_BANDLIMIT_SAWTOOTH_REVERSE 10
#define WAVEFORM_BANDLIMIT_SQUARE 11
#define WAVEFORM_BANDLIMIT_PULSE  12

#define AUDIO_INPUT_LINEIN      0
#define AUDIO_INPUT_MIC         1
#define AUDIO_HEADPHONE_DAC     0
#define AUDIO_HEADPHONE_LINEIN  1

enum AudioFilterLadderInterpolation {
    LADDER_FILTER_INTERPOLATION_LINEAR,
    LADDER_FILTER_INTERPOLATION_FIR_POLY
};

#define AudioMemory(num)            bl_audio_memory(num)
#define AudioProcessorUsage()       bl_audio_stat(BL_AUDIO_STAT_CPU)
#define AudioProcessorUsageMax()    bl_audio_stat(BL_AUDIO_STAT_CPU_MAX)
#define AudioProcessorUsageMaxReset() ((void)bl_audio_stat(BL_AUDIO_STAT_CPU_MAX_RESET))
#define AudioMemoryUsage()          ((int)bl_audio_stat(BL_AUDIO_STAT_MEMORY))
#define AudioMemoryUsageMax()       ((int)bl_audio_stat(BL_AUDIO_STAT_MEMORY_MAX))
#define AudioMemoryUsageMaxReset()  ((void)bl_audio_stat(BL_AUDIO_STAT_MEMORY_MAX_RESET))
static inline void AudioNoInterrupts() { bl_audio_interrupts(0); }
static inline void AudioInterrupts() { bl_audio_interrupts(1); }

/* Every object: a handle to the real one in Baseline (negative if it could not be made). */
class AudioObjectProxy {
public:
    int bl_handle() const { return h_; }
protected:
    explicit AudioObjectProxy(int type, const bl_audio_arg_t *args = 0, int nargs = 0)
        : h_(bl_audio_create(type, args, nargs)) {}
    void bl_call(int method, const bl_audio_arg_t *args, int nargs, bl_audio_arg_t *ret = 0)
    {
        bl_audio_call(h_, method, args, nargs, ret);
    }
    int h_;
};

class AudioStream : public AudioObjectProxy {
public:
    float processorUsage() { bl_audio_arg_t r; r.f = 0; bl_call(1000, 0, 0, &r); return r.f; }
    float processorUsageMax() { bl_audio_arg_t r; r.f = 0; bl_call(1001, 0, 0, &r); return r.f; }
    void processorUsageMaxReset() { bl_call(1002, 0, 0); }
protected:
    explicit AudioStream(int type, const bl_audio_arg_t *args = 0, int nargs = 0) : AudioObjectProxy(type, args, nargs) {}
};

class AudioControl : public AudioObjectProxy {
protected:
    explicit AudioControl(int type, const bl_audio_arg_t *args = 0, int nargs = 0) : AudioObjectProxy(type, args, nargs) {}
};

class AudioConnection {
public:
    AudioConnection() : h_(-1) {}
    AudioConnection(AudioStream &source, AudioStream &destination) : h_(-1) { connect(source, 0, destination, 0); }
    AudioConnection(AudioStream &source, unsigned char sourceOutput, AudioStream &destination, unsigned char destinationInput)
        : h_(-1) { connect(source, sourceOutput, destination, destinationInput); }
    int connect(AudioStream &source, AudioStream &destination) { return connect(source, 0, destination, 0); }
    int connect(AudioStream &source, unsigned char sourceOutput, AudioStream &destination, unsigned char destinationInput)
    {
        if (h_ >= 0) {
            bl_audio_disconnect(h_);
        }
        h_ = bl_audio_connect(source.bl_handle(), sourceOutput, destination.bl_handle(), destinationInput);
        return h_ >= 0 ? 0 : 4;
    }
    int connect() { return h_ >= 0 && bl_audio_reconnect(h_) == BL_OK ? 0 : 4; }
    int disconnect() { return h_ >= 0 && bl_audio_disconnect(h_) == BL_OK ? 0 : 1; }
private:
    int h_;
};

'''


def sdk_method(m):
    params = m["params"]
    decl = ", ".join(p.sdk_decl() for p in params)
    ret = m["ret"]
    body = []
    if params:
        body.append(f"bl_audio_arg_t a[{len(params)}];")
        body += [p.sdk_store(i) for i, p in enumerate(params)]
    args = ("a", str(len(params))) if params else ("0", "0")
    if ret == "void":
        body.append(f"bl_call({m['id']}, {args[0]}, {args[1]});")
    else:
        mem = member_of(ret)
        body.append(f"bl_audio_arg_t r; r.{mem} = 0;")
        body.append(f"bl_call({m['id']}, {args[0]}, {args[1]}, &r);")
        if mem == "p":
            body.append(f"return ({ret})r.p;")
        elif ret == "bool":
            body.append("return r.i != 0;")
        else:
            body.append(f"return ({ret})r.{mem};")
    return f"    {ret} {m['name']}({decl}) {{ {' '.join(body)} }}\n"


def gen_sdk(classes):
    o = [HEADER, SDK_PROLOGUE]
    for c in classes:
        o.append("\n#define BL_AUDIO_T_%s %d\n" % (c["name"], c["type"]))
    o.append("\n")
    for c in classes:
        base = "AudioStream" if c["kind"] == "stream" else "AudioControl"
        o.append(f"class {c['name']} : public {base} {{\npublic:\n")
        if c["name"] == "AudioPlayQueue":
            o.append("    enum behaviour_e { ORIGINAL, NON_STALLING };\n")
        if c["ctor"]:
            decl = ", ".join(p.sdk_decl() for p in c["ctor"])
            stores = " ".join(p.sdk_store(i) for i, p in enumerate(c["ctor"]))
            n = len(c["ctor"])
            o.append(f"    {c['name']}({decl}) : {base}(BL_AUDIO_T_{c['name']}, ctor_args({', '.join(p.name for p in c['ctor'])}), {n}) {{}}\n")
            o.append("private:\n")
            # The constructor's arguments are packed before the base is built.
            o.append(f"    static const bl_audio_arg_t *ctor_args({', '.join(('int' if p.enum else p.type) + ' ' + p.name for p in c['ctor'])})\n"
                     f"    {{\n        static bl_audio_arg_t a[{n}];\n        {stores}\n        return a;\n    }}\npublic:\n")
        else:
            o.append(f"    {c['name']}() : {base}(BL_AUDIO_T_{c['name']}) {{}}\n")
        for m in c["methods"]:
            o.append(sdk_method(m))
        o.append("};\n\n")
    o.append("#endif /* __cplusplus */\n#endif /* BASELINE_AUDIO_H */\n")
    return "".join(o)


# ---------------------------------------------------------------- Baseline side

def baseline_call(c, m):
    params = m["params"]
    args = ", ".join(p.baseline_arg(i) for i, p in enumerate(params))
    need = f"if (n < {len(params)}) return BL_ERR_ARG; " if params else ""
    call = f"o->{m['name']}({args})"
    if m["ret"] == "void":
        return f"        case {m['id']}: {need}{call}; return BL_OK;\n"
    mem = member_of(m["ret"])
    conv = {"p": "(const void *)", "f": "(float)", "i": "(int32_t)"}[mem]
    return f"        case {m['id']}: {{ {need}auto v = {call}; if (r) r->{mem} = {conv}v; return BL_OK; }}\n"


def gen_dispatch(classes):
    o = [HEADER,
         "/* Included by bl_teensy_audio.cpp. bl_audio_new(): construct an object by type\n"
         " * number; bl_audio_dispatch(): call a method by number. Stream objects are\n"
         " * passed as AudioStream *, controls as AudioControl *. */\n\n"]
    o.append("static void *bl_audio_new(int type, const bl_audio_arg_t *a, int n, bool *is_stream)\n{\n"
             "    (void)a; (void)n;\n    switch (type) {\n")
    for c in classes:
        if c["cond"]:
            o.append(f"#if defined({c['cond']})\n")
        stream = "true" if c["kind"] == "stream" else "false"
        cast = "AudioStream" if c["kind"] == "stream" else "AudioControl"
        if c["ctor"]:
            args = ", ".join(p.baseline_arg(i) for i, p in enumerate(c["ctor"]))
            o.append(f"    case {c['type']}: *is_stream = {stream}; "
                     f"return n >= {len(c['ctor'])} ? ({cast} *)new {c['name']}({args}) : ({cast} *)new {c['name']}();\n")
        else:
            o.append(f"    case {c['type']}: *is_stream = {stream}; return ({cast} *)new {c['name']}();\n")
        if c["cond"]:
            o.append("#endif\n")
    o.append("    default: return NULL;\n    }\n}\n\n")
    o.append("static int bl_audio_dispatch(int type, void *base, int method, const bl_audio_arg_t *a, int n, bl_audio_arg_t *r)\n{\n"
             "    (void)a; (void)n; (void)r;\n    switch (type) {\n")
    for c in classes:
        if not c["methods"]:
            continue
        if c["cond"]:
            o.append(f"#if defined({c['cond']})\n")
        cast = "AudioStream" if c["kind"] == "stream" else "AudioControl"
        o.append(f"    case {c['type']}: {{\n        {c['name']} *o = static_cast<{c['name']} *>(({cast} *)base);\n"
                 "        switch (method) {\n")
        for m in c["methods"]:
            o.append(baseline_call(c, m))
        o.append("        default: return BL_ERR_UNSUPPORTED;\n        }\n    }\n")
        if c["cond"]:
            o.append("#endif\n")
    o.append("    default: return BL_ERR_UNSUPPORTED;\n    }\n}\n")
    return "".join(o)


def write(path, text):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


def main():
    classes = parse_spec()
    print(f"{len(classes)} audio classes, {sum(len(c['methods']) for c in classes)} methods")
    write(OUT_SDK, gen_sdk(classes))
    write(OUT_DISPATCH, gen_dispatch(classes))


if __name__ == "__main__":
    main()
