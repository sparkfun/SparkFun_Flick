#!/usr/bin/env python3
"""Generate the Baseline API table from api/baseline_api.txt.

Outputs:
  sdk/include/baseline_api.h      bl_api_t + sketch-side wrappers
  baseline/src/gen/bl_impl.h      prototypes Baseline must implement (bl_impl_<field>)
  baseline/src/gen/api_table.c    the table instance Baseline passes to sketches
  baseline/src/gen/bl_impl_stubs.inc  stubs for chips without the hardware (no radio)
  baseline/src/gen/bl_impl_weak.inc   every entry as a weak stub (a new chip family's starting point)
  docs/API.md                     API reference

ABI check: api/abi.lock records the released table. Every locked entry must
still be present, in the same position, with the same signature. New entries
may only be appended, with a minor above every locked minor.

Usage:
  python flick/tools/gen_api.py            generate + check against abi.lock
  python flick/tools/gen_api.py --check    check only, write nothing (for CI)
  python flick/tools/gen_api.py --lock     generate, then record the current table as released
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "api" / "baseline_api.txt"
LOCK = ROOT / "api" / "abi.lock"
OUT_API_H = ROOT / "sdk" / "include" / "baseline_api.h"
OUT_IMPL_H = ROOT / "baseline" / "src" / "gen" / "bl_impl.h"
OUT_TABLE_C = ROOT / "baseline" / "src" / "gen" / "api_table.c"
OUT_STUBS = ROOT / "baseline" / "src" / "gen" / "bl_impl_stubs.inc"
OUT_WEAK = ROOT / "baseline" / "src" / "gen" / "bl_impl_weak.inc"
OUT_DOC = ROOT / "docs" / "API.md"

HEADER = "/* GENERATED by tools/gen_api.py from api/baseline_api.txt - DO NOT EDIT */\n"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def norm(s):
    """Normalize a C type/param string so whitespace differences don't matter."""
    s = re.sub(r"\s+", " ", s.strip())
    s = re.sub(r"\s*\*\s*", " *", s)
    s = re.sub(r"\s*,\s*", ", ", s)
    return s


class Entry:
    def __init__(self, lineno, minor, ret, field, params, wrapper, doc):
        self.lineno, self.minor, self.ret, self.field = lineno, minor, norm(ret), field
        self.params, self.wrapper, self.doc = norm(params), wrapper, doc.strip()

    @property
    def variadic(self):
        return self.params.endswith("...")

    def arg_names(self):
        if self.params == "void":
            return []
        names = []
        for p in self.params.split(","):
            p = p.strip()
            if p == "...":
                continue
            m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*$", p)
            if not m or m.group(1) == p:
                raise SystemExit(f"{SPEC.name}:{self.lineno}: parameter '{p}' needs a name")
            names.append(m.group(1))
        return names

    def sig(self):
        return f"{self.minor}|{self.ret}|{self.field}|{self.params}"


def parse_spec():
    major = None
    entries = []
    for lineno, raw in enumerate(SPEC.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"abi_major\s*=\s*(\d+)$", line)
        if m:
            major = int(m.group(1))
            continue
        parts = [p.strip() for p in line.split("|", 5)]
        if len(parts) != 6:
            raise SystemExit(f"{SPEC.name}:{lineno}: expected 6 '|'-separated fields")
        minor, ret, field, params, wrapper, doc = parts
        if not minor.isdigit():
            raise SystemExit(f"{SPEC.name}:{lineno}: minor must be an integer")
        if not IDENT.match(field):
            raise SystemExit(f"{SPEC.name}:{lineno}: bad field name '{field}'")
        if wrapper != "-" and not IDENT.match(wrapper.removeprefix("@")):
            raise SystemExit(f"{SPEC.name}:{lineno}: bad wrapper name '{wrapper}'")
        entries.append(Entry(lineno, int(minor), ret, field, params, wrapper, doc))
    if major is None:
        raise SystemExit(f"{SPEC.name}: missing 'abi_major = N'")
    seen = set()
    last_minor = 0
    for e in entries:
        if e.field in seen:
            raise SystemExit(f"{SPEC.name}:{e.lineno}: duplicate field '{e.field}'")
        seen.add(e.field)
        if e.minor < last_minor:
            raise SystemExit(f"{SPEC.name}:{e.lineno}: minor numbers must not decrease")
        last_minor = e.minor
        e.arg_names()  # validates names
    return major, entries


def check_lock(major, entries):
    if not LOCK.exists():
        return None
    lines = [l for l in LOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    locked_major = int(lines[0].split("=")[1])
    locked = lines[1:]
    if locked_major != major:
        print(f"note: abi_major changed {locked_major} -> {major}; lock ignored (run --lock at release)")
        return None
    errors = []
    for i, sig in enumerate(locked):
        if i >= len(entries):
            errors.append(f"entry #{i} removed: {sig}")
        elif entries[i].sig() != sig:
            errors.append(f"entry #{i} changed:\n    locked: {sig}\n    now:    {entries[i].sig()}")
    max_locked_minor = max((int(s.split("|")[0]) for s in locked), default=-1)
    for e in entries[len(locked):]:
        if e.minor <= max_locked_minor:
            errors.append(f"new entry '{e.field}' must use minor > {max_locked_minor}")
    if errors:
        print("ABI CHECK FAILED (the table must stay append-only within abi_major):", file=sys.stderr)
        for err in errors:
            print("  " + err, file=sys.stderr)
        print("Fix the spec, or bump abi_major if this break is intended.", file=sys.stderr)
        raise SystemExit(1)
    return len(locked)


def fnptr(e, name):
    return f"{e.ret} (*{name})({e.params})"


# Sketch-side wrappers exist only on boards that have the feature (bl_target.h's
# BL_PLATFORM_* / BL_HAS_* macros), so a sketch that calls WiFi or BLE on a
# Teensy, or Teensy's audio on an ESP32, fails to compile instead of failing
# quietly at run time. The table entries themselves are the same everywhere.
# Field prefix -> required macro. (ledc_, ps_ and sleep_ stay: the SDK builds
# Servo, tone() and the Teensy names on them.)
WRAPPER_PREFIX_REQUIRES = [
    (("wifi_", "web_", "mdns_", "mqtt_", "dns_", "ota_"), "BL_HAS_WIFI"),
    (("http_", "net_", "tcp_", "udp_"), "BL_HAS_NET"),       # sockets and HTTP: WiFi or Ethernet
    (("eth_",), "BL_HAS_ETHERNET"),
    (("espnow_",), "BL_HAS_ESPNOW"),
    (("ble_",), "BL_HAS_BLE"),
    (("bt_",), "BL_HAS_BT_CLASSIC"),
    (("touch_",), "BL_HAS_TOUCH"),
    (("dac_",), "BL_HAS_DAC"),
    (("usb_",), "BL_HAS_USB_DEVICE"),
    (("i2s_",), "BL_PLATFORM_ESP32"),
    (("rgb_", "led_strip_"), "BL_HAS_LED_STRIP"),
    (("audio_",), "BL_HAS_AUDIO"),
    (("usbh_",), "BL_HAS_USB_HOST"),
    (("isr_", "dma_channel_"), "BL_TARGET_SKETCH_ISR"),
    (("task_", "sem_", "queue_"), "BL_HAS_RTOS"),
    (("idf_", "update_"), "BL_PLATFORM_ESP32"),
]
# Arduino-ESP32 names (not bl_*) that would mislead elsewhere.
WRAPPER_NAME_REQUIRES = {
    "analogReadMilliVolts": "BL_PLATFORM_ESP32", "rgbLedWrite": "BL_HAS_LED_STRIP",
    "ps_malloc": "BL_PLATFORM_ESP32", "ps_calloc": "BL_PLATFORM_ESP32", "ps_realloc": "BL_PLATFORM_ESP32",
    "temperatureRead": "BL_PLATFORM_ESP32",
}


def requires_expr(macros):
    """A macro, or a tuple of macros any one of which will do, as a #if expression."""
    if isinstance(macros, str):
        macros = (macros,)
    return " || ".join(f"defined({m})" for m in macros)


def wrapper_requires(e):
    if e.field == "usb_devices":
        return None     # for Baseline's INFO, not a sketch feature
    if e.wrapper in WRAPPER_NAME_REQUIRES:
        return requires_expr(WRAPPER_NAME_REQUIRES[e.wrapper])
    for prefixes, macro in WRAPPER_PREFIX_REQUIRES:
        if e.field.startswith(prefixes):
            return requires_expr(macro)
    return None


def gen_api_h(major, minor, entries):
    o = [HEADER, "#ifndef BASELINE_API_H\n#define BASELINE_API_H\n\n",
         '#include "baseline_types.h"\n\n',
         f"#define BL_ABI_MAJOR {major}\n#define BL_ABI_MINOR {minor}\n\n",
         "typedef struct bl_api {\n",
         "    uint16_t abi_major;\n    uint16_t abi_minor;\n",
         "    uint32_t struct_size;       /* sizeof(bl_api_t) in the running Baseline */\n"]
    cur = None
    for e in entries:
        if e.minor != cur:
            cur = e.minor
            o.append(f"\n    /* ---- added in {major}.{cur} ---- */\n")
        o.append(f"    {fnptr(e, e.field)};\n")
    o.append("} bl_api_t;\n\n")

    o.append("#ifndef BASELINE_FIRMWARE\n")
    o.append("/* ---------------- Sketch side ---------------- */\n\n")
    o.append("/* Set by sketch_entry() before any sketch code runs. */\n")
    o.append("extern const bl_api_t *BL;\n\n")
    o.append("/* The board's features (BL_PLATFORM_*, BL_HAS_*) decide which wrappers exist. */\n")
    o.append("#include \"bl_target.h\"\n\n")
    o.append("/* True if the running Baseline provides `field` (for entries newer than the\n"
             "   sketch's required minor). */\n")
    o.append("#define BL_HAS(field) (offsetof(bl_api_t, field) < BL->struct_size)\n\n")
    o.append(r'''/* The oldest Baseline a sketch runs on. Each call through the table leaves a
   marker, a byte holding the minor version that added the entry, in a section
   of its own (.bl_need.N) that the calling code refers to. Linking drops the
   markers of code that isn't used, and flick stamps the sketch header with the
   largest one left (sdk/ld/sketch_esp.ld.in collects them, make_image() in
   flick.py reads them), so a sketch runs on every Baseline that has the
   entries it calls. Call the table with BL_CALL(field)(...); a plain
   BL->field(...) leaves no marker: only for a call guarded by BL_HAS(field). */
#define BL_NEED_STR_(x) #x
#define BL_NEED_(minor) __asm__ volatile(".pushsection .bl_need.%=,\"a\"\n" \
    ".Lbl_need%=: .byte " BL_NEED_STR_(minor) "\n.popsection\n" \
    ".reloc ., BFD_RELOC_NONE, .Lbl_need%=" ::)
#define BL_NEED(minor) BL_NEED_(minor)
#define BL_CALL(field) (__extension__({ BL_NEED(BL_MINOR_##field); BL->field; }))

/* The minor version that added each entry. */
''')
    for e in entries:
        o.append(f"#define BL_MINOR_{e.field} {e.minor}\n")
    o.append("\n")
    for e in entries:
        if e.wrapper == "-" or e.wrapper.startswith("@"):     # @name: written by hand in baseline.h
            continue
        need = wrapper_requires(e)
        if need:
            o.append(f"#if {need}\n")
        o.append(f"/* {e.doc} */\n")
        if e.variadic:
            o.append(f"#define {e.wrapper}(...) (BL_CALL({e.field})(__VA_ARGS__))\n")
        else:
            args = ", ".join(e.arg_names())
            ret = "" if e.ret == "void" else "return "
            o.append(f"static inline {e.ret} {e.wrapper}({e.params}) {{ {ret}BL_CALL({e.field})({args}); }}\n")
        if need:
            o.append("#endif\n")
    o.append("#endif /* BASELINE_FIRMWARE */\n\n#endif /* BASELINE_API_H */\n")
    return "".join(o)


def gen_impl_h(entries):
    o = [HEADER, "#pragma once\n\n#define BASELINE_FIRMWARE 1\n#include \"baseline_api.h\"\n\n",
         "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n",
         "extern const bl_api_t bl_api_table;\n\n"]
    for e in entries:
        o.append(f"{e.ret} bl_impl_{e.field}({e.params});\n")
    o.append("\n#ifdef __cplusplus\n}\n#endif\n")
    return "".join(o)


def gen_table_c(entries):
    o = [HEADER, '#include "bl_impl.h"\n\n',
         "const bl_api_t bl_api_table = {\n",
         "    .abi_major = BL_ABI_MAJOR,\n    .abi_minor = BL_ABI_MINOR,\n",
         "    .struct_size = sizeof(bl_api_t),\n"]
    for e in entries:
        o.append(f"    .{e.field} = bl_impl_{e.field},\n")
    o.append("};\n")
    return "".join(o)


# Stub groups for chips without the hardware (the ESP32-P4 has no radio). A
# source file that cannot build on such a chip defines BL_STUB_<GROUP> 1 and
# includes gen/bl_impl_stubs.inc instead of its real code. A group is every
# entry whose field starts with one of its prefixes, plus the named fields.
STUB_GROUPS = {
    "WIFI": (("wifi_",), ("http_request", "http_get", "net_resolve", "net_if_get", "net_if_set", "net_event_name")),
    "BLE": (("ble_",), ()),
    "ESPNOW": (("espnow_",), ()),
    # Teensy-only entries: sketch interrupt handlers, DMA channels, the Audio library (ABI 1.8), USB host (1.9).
    "TEENSY": (("isr_", "dma_channel_", "audio_", "usbh_", "eth_"), ()),
}
# What a stub returns. Queries answer "nothing there" (so `while (available())`
# ends); actions report BL_ERR_UNSUPPORTED.
STUB_RETURNS = [
    (r"^wifi_status$", "BL_WIFI_NO_SHIELD"),
    (r"(_read|_peek|^wifi_event_take|^wifi_event_take_info|^espnow_send_status)$", "-1"),
    (r"(available|connected|_count|running|^ble_event_take|^ble_serial_write|rssi|channel|stations|get_mode|ssid|get_value|"
     r"^espnow_receive|^espnow_receive_info)$", "0"),
]


def stub_body(e):
    if e.ret == "void":
        return "{}"
    if e.ret.endswith("*"):
        return "{ return NULL; }"
    if e.ret != "int":
        return "{ return 0; }"
    for pattern, value in STUB_RETURNS:
        if re.search(pattern, e.field):
            return f"{{ return {value}; }}"
    return "{ return BL_ERR_UNSUPPORTED; }"


def gen_stubs(entries):
    o = [HEADER,
         "/* Stub implementations for chips without the hardware. In a source file:\n"
         " *     #define BL_STUB_WIFI 1\n *     #include \"gen/bl_impl_stubs.inc\"\n */\n"]
    for group, (prefixes, names) in STUB_GROUPS.items():
        members = [e for e in entries if e.field.startswith(prefixes) or e.field in names]
        o.append(f"\n#if defined(BL_STUB_{group}) && BL_STUB_{group}\n")
        for e in members:
            o.append(f"extern \"C\" {e.ret} bl_impl_{e.field}({e.params}) {stub_body(e)}\n")
        o.append(f"#endif /* BL_STUB_{group} */\n")
    return "".join(o)


def gen_weak(entries):
    """Every entry as a weak stub, for a Baseline that is not built from
    baseline/src (the Teensy port): it implements what it supports, and the
    rest of the table answers like a chip without the hardware."""
    o = [HEADER,
         "/* Weak stubs for every entry. Include it from one C++ file; a strong\n"
         " * bl_impl_<field> anywhere in the build replaces the stub. */\n"]
    for e in entries:
        o.append(f"extern \"C\" __attribute__((weak)) {e.ret} bl_impl_{e.field}({e.params}) {stub_body(e)}\n")
    return "".join(o)


def gen_doc(major, minor, entries):
    o = [f"# Baseline API reference (ABI {major}.{minor})\n\n",
         "Generated from `api/baseline_api.txt` by `tools/gen_api.py`. Do not edit.\n\n",
         "Include `baseline.h` in your sketch. Call the **Sketch name** column. "
         "Every call goes through the `BL` table pointer.\n\n",
         "| Sketch name | Signature | Since | Description |\n|---|---|---|---|\n"]
    for e in entries:
        name = e.wrapper.removeprefix("@") if e.wrapper != "-" else f"BL->{e.field}"
        o.append(f"| `{name}` | `{e.ret} {e.field}({e.params})` | {major}.{e.minor} | {e.doc} |\n")
    return "".join(o)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="check only, write nothing")
    ap.add_argument("--lock", action="store_true", help="record the current table as released")
    args = ap.parse_args()

    major, entries = parse_spec()
    minor = max((e.minor for e in entries), default=0)
    n_locked = check_lock(major, entries)
    print(f"ABI {major}.{minor}: {len(entries)} entries"
          + (f" ({n_locked} locked)" if n_locked is not None else " (no lock yet)"))
    if args.check:
        return
    write(OUT_API_H, gen_api_h(major, minor, entries))
    write(OUT_IMPL_H, gen_impl_h(entries))
    write(OUT_TABLE_C, gen_table_c(entries))
    write(OUT_STUBS, gen_stubs(entries))
    write(OUT_WEAK, gen_weak(entries))
    write(OUT_DOC, gen_doc(major, minor, entries))
    if args.lock or not LOCK.exists():
        write(LOCK, f"abi_major={major}\n" + "".join(e.sig() + "\n" for e in entries))


if __name__ == "__main__":
    main()
