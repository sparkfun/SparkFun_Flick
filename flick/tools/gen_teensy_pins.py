#!/usr/bin/env python3
"""Write chips/imxrt1062/sdk/bl_teensy_pins.h: each Teensy board's pin -> fast
GPIO port and bit, from Teensyduino's cores/teensy4/core_pins.h.

  python flick/tools/gen_teensy_pins.py [path/to/core_pins.h]

Without a path, the core_pins.h of the Teensyduino flick builds Teensy sketches
with. Run it again when a Teensyduino update changes the pin tables (it never
has for the 4.x boards).
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import flick  # noqa: E402

OUT = flick.ROOT / "chips" / "imxrt1062" / "sdk" / "bl_teensy_pins.h"
# Teensyduino's board macro -> BL_BOARD_TEENSY_MODEL (the targets' bl_board.h).
BOARDS = [("ARDUINO_TEENSY40", 0x24, "Teensy 4.0"),
          ("ARDUINO_TEENSY41", 0x25, "Teensy 4.1"),
          ("ARDUINO_TEENSY_MICROMOD", 0x26, "MicroMod Teensy")]


def core_pins():
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    gcc = flick.find_gcc(flick.load_target("teensy40"))
    return flick.teensy_core_dir(gcc) / "core_pins.h"


def tables(text):
    out = []
    for macro, model, name in BOARDS:
        m = re.search(r"#(?:el)?if defined\(__IMXRT1062__\) && defined\(" + macro + r"\)\n(.*?)\n#(?:elif|endif)",
                      text, re.S)
        if not m:
            sys.exit(f"{macro}: section not found in core_pins.h")
        sec = m.group(1)
        n = int(re.search(r"#define CORE_NUM_DIGITAL\s+(\d+)", sec).group(1))
        bits = {int(p): int(b) for p, b in re.findall(r"#define CORE_PIN(\d+)_BIT\s+(\d+)", sec)}
        ports = {int(p): int(g) for p, g in re.findall(r"#define CORE_PIN(\d+)_PORTREG\s+GPIO(\d)_DR\b", sec)}
        entries = []
        for pin in range(n):
            port, bit = ports[pin], bits[pin]
            if not 6 <= port <= 9:
                sys.exit(f"{macro} pin {pin}: GPIO{port} is not a fast GPIO")
            entries.append((port - 6) << 5 | bit)
        out.append((model, name, n, entries))
    return out


def main():
    src = core_pins()
    rows = tables(src.read_text(encoding="utf-8", errors="replace"))
    lines = ["/*",
             " * bl_teensy_pins.h - each Teensy board's pins on the fast GPIO ports (GPIO6-9),",
             " * for digitalWriteFast() and friends (baseline_teensy.h). One byte a pin:",
             " * (port - 6) << 5 | bit. Generated by tools/gen_teensy_pins.py from",
             " * Teensyduino's core_pins.h: don't edit.",
             " */",
             "#pragma once",
             "#include <stdint.h>",
             ""]
    for i, (model, name, n, entries) in enumerate(rows):
        kw = "#if" if i == 0 else "#elif"
        lines.append(f"{kw} BL_BOARD_TEENSY_MODEL == 0x{model:02X}      /* {name} */")
        lines.append(f"#define BL_TEENSY_NUM_DIGITAL {n}")
        lines.append("static const uint8_t bl_teensy_pins[BL_TEENSY_NUM_DIGITAL] = {")
        for j in range(0, n, 10):
            chunk = ", ".join(f"0x{e:02X}" for e in entries[j:j + 10])
            lines.append(f"    {chunk},{'':<{max(0, 60 - len(chunk))}} /* {j}-{min(j + 9, n - 1)} */")
        lines.append("};")
    lines += ["#else", '#error "bl_teensy_pins.h: unknown BL_BOARD_TEENSY_MODEL"', "#endif", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(flick.ROOT.parent)} from {src}")


if __name__ == "__main__":
    main()
